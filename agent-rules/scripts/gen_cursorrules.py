#!/usr/bin/env python3
"""Generate .cursorrules from AGENTS.md and agent-rules/rules/*.md.

.cursorrules is read by Cursor and by any tool that takes the rules as one file (for example a CI
pipeline that sends them to a model), so every tool follows the same rules as agent sessions.
Never edit .cursorrules by hand.

Usage: gen_cursorrules.py [--check]   (--check exits 1 when .cursorrules is stale)
"""
import glob
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, ".cursorrules")

HEADER = """# .cursorrules — GENERATED, do not edit

Generated by `agent-rules/scripts/gen_cursorrules.py` from `AGENTS.md` and `agent-rules/rules/*.md`.
Edit those files and regenerate; the gate fails when this file is stale.

"""


def build():
    parts = [HEADER, open(os.path.join(ROOT, "AGENTS.md"), encoding="utf-8").read().rstrip() + "\n"]
    for path in sorted(glob.glob(os.path.join(ROOT, "agent-rules", "rules", "*.md"))):
        body = open(path, encoding="utf-8").read().rstrip()
        parts.append("\n---\n\n<!-- %s -->\n\n%s\n" % (os.path.relpath(path, ROOT), body))
    return "".join(parts)


def main():
    content = build()
    size = len(content.encode("utf-8"))
    if "--check" in sys.argv[1:]:
        current = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if current != content:
            print("FAIL: .cursorrules is stale — run python3 agent-rules/scripts/gen_cursorrules.py")
            return 1
        print(".cursorrules: up to date (%d bytes)" % size)
    else:
        open(OUT, "w", encoding="utf-8").write(content)
        print("written .cursorrules (%d bytes)" % size)
    return 0


if __name__ == "__main__":
    sys.exit(main())
