#!/usr/bin/env python3
"""Generate specifications/features/SPEC_INDEX.md from the epic specs and the task registry.

Usage: gen_spec_index.py [--check]
--check exits with 1 when the committed index is stale. Exit 3 means a required tool is missing.
"""
import os
import re
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(__file__))
from specs_lib import REGISTRY, SPECS, ToolMissing, load_yaml  # noqa: E402

INDEX = os.path.join(SPECS, "features", "SPEC_INDEX.md")


def build():
    reg = load_yaml(REGISTRY)
    tasks = {}
    for f in reg.get("features") or []:
        tasks.setdefault(f.get("epic"), []).append(f)
    lines = [
        "# Spec index",
        "",
        "Generated by `agent-rules/scripts/gen_spec_index.py` — do not edit by hand.",
        "Find a spec here, not by guessing the file name. Statuses come from `FEATURE_REGISTRY.yaml`.",
        "",
        "| Epic | Title | Spec | Tasks |",
        "|---|---|---|---|",
    ]
    for epic in reg.get("epics") or []:
        spec = epic.get("spec", "")
        path = os.path.join(SPECS, spec)
        title = epic.get("title", "")
        if os.path.isfile(path):
            first = open(path, encoding="utf-8").readline().strip()
            m = re.match(r"^#\s+\S+\s+—\s+(.+)$", first)
            if m:
                title = m.group(1)
        task_list = ", ".join("`%s` %s" % (t["id"], t["status"]) for t in tasks.get(epic.get("id"), []))
        lines.append("| `%s` | %s | [%s](%s) | %s |" % (
            epic.get("id"), title, os.path.basename(spec), os.path.basename(spec), task_list or "—"))
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    try:
        content = build()
    except ToolMissing as e:
        print("SKIP: %s" % e)
        return 3
    except ValueError as e:
        print("FAIL: %s" % e)
        return 1
    if check:
        current = open(INDEX, encoding="utf-8").read() if os.path.isfile(INDEX) else ""
        if current != content:
            print("FAIL: SPEC_INDEX.md is stale — run python3 agent-rules/scripts/gen_spec_index.py")
            return 1
        print("Spec index: up to date")
        return 0
    open(INDEX, "w", encoding="utf-8").write(content)
    print("written", os.path.relpath(INDEX))
    return 0


if __name__ == "__main__":
    sys.exit(main())
